for c=0xA0,0xBE do if c~=0xB7 then LOWER[string.char(0xC3,c)]=string.char(0xC3,c-32)end end
for i=0,31 do
    local lower=i<16 and string.char(0xD0,0xB0+i)or string.char(0xD1,0x80+i-16)
    LOWER[lower]=string.char(0xD0,0x90+i)
end
function ns.Upper(text)return(tostring(text):upper():gsub("[\195\208\209][\128-\191]",LOWER))end
