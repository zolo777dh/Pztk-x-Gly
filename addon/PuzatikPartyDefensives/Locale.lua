-- Same English words name different specs (Holy, Frost, Protection, Restoration): each class is
-- looked up on its own tab, and the short words translate to the same Russian anyway.
for _,set in ipairs({{ru,SPECS,2},{fr,SPECS_FR,3},{de,SPECS_DE,4}})do
    local t,specs,i=set[1],set[2],set[3]
    for class,names in pairs(CLASSES)do
        t[names[1]]=names[i]
        for _,spec in ipairs(ns.ClassSpecs[class]or{})do
            local full=ns.Catalog.specs[spec]
            if full and specs[spec]then
                t[full]=specs[spec].." ("..names[i]..")"
                t[full:gsub(" "..names[1].."$","")]=specs[spec]
            end
        end
    end
end
local TABLES={ruRU=ru,frFR=fr,deDE=de}
function ns.Language()
    local choice=PuzatikPartyDefensivesDB and PuzatikPartyDefensivesDB.lang
    if choice=="enUS"or TABLES[choice]then return choice end
    local client=GetLocale and GetLocale()
    return TABLES[client]and client or"enUS"
end
function ns.SetLanguage(choice)
    PuzatikPartyDefensivesDB=PuzatikPartyDefensivesDB or{}
    PuzatikPartyDefensivesDB.lang=(choice=="enUS"or TABLES[choice])and choice or nil
end
function ns.L(text)
    local t=TABLES[ns.Language()]
    return t and t[text]or text
end
ns.LocaleTables=TABLES
